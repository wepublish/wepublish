// simulate database with a fixed pool of articles
const ARTICLE_POOL = Array.from({ length: 150 }, (_, i) => ({
  id: `article_pool_${i + 1}`,
  title: `Article ${i + 1}`,
}));

const mockArticleService = {
  getArticles: vi.fn().mockImplementation(async ({ take, filter }) => {
    const excludedIds = filter?.excludeIds || [];

    // simulate async database delay with random timing to expose race conditions while loading teasers
    await new Promise(resolve => setTimeout(resolve, Math.random() * 50));

    // simulate database: return articles from pool that are NOT in excludeIds
    const availableArticles = ARTICLE_POOL.filter(
      a => !excludedIds.includes(a.id)
    );
    const articles = availableArticles.slice(0, take);

    return { nodes: articles };
  }),
};

const mockManualTeaserSlotsBlock = (articleID: string) =>
  ({
    autofillConfig: { enabled: false, teaserType: TeaserType.Article },
    slots: [
      {
        type: TeaserSlotType.Manual,
        teaser: mockArticleTeaser({ articleID }),
      },
    ],
    type: BlockType.TeaserSlots,
  }) as unknown as BaseBlock<BlockType>;

const mockBlockTemplateBlock = (templateId: string) =>
  ({
    type: BlockType.BlockTemplate,
    templateId,
  }) as unknown as BaseBlock<BlockType>;

let mockTemplates: Record<string, { id: string; blocks: unknown[] }> = {};

const mockBlockTemplateDataloader = {
  load: vi.fn(async (id: string) => mockTemplates[id] ?? null),
};

describe('BlockTreeLoader', () => {
  let service: BlockTreeLoader;

  beforeEach(async () => {
    vi.clearAllMocks();
    const module: TestingModule = await Test.createTestingModule({
      providers: [
        BlockTreeLoader,
        { provide: EventService, useValue: mockEventService },
        { provide: ArticleService, useValue: mockArticleService },
        {
          provide: BlockTemplateDataloaderService,
          useValue: mockBlockTemplateDataloader,
        },
      ],
    }).compile();

    service = await module.resolve<BlockTreeLoader>(BlockTreeLoader);
  });

  const extractTeasers = (block: FullTeaserSlotsBlockFragment): string[] => {
    const teaserIds: string[] = [];
    for (const t of block.teasers) {
      if (t && t.type === TeaserType.Article) {
        const teaser = t as FullArticleTeaserFragment;
        const id = teaser.article?.id || teaser.articleID;
        if (id) {
          teaserIds.push(id);
        }
      }
    }
    return teaserIds;
  };

  const processBlock = (block: BaseBlock<BlockType>) => {
    if (isFlexBlock(block)) {
      const teaserIds: string[] = [];
      for (const nestedBlock of (block as FlexBlock).blocks) {
        teaserIds.push(
          ...processBlock(
            (nestedBlock as BlockWithAlignment).block as BaseBlock<BlockType>
          )
        );
      }
      return teaserIds;
    }

    if (block.type === BlockType.BlockTemplate) {
      const teaserIds: string[] = [];
      for (const nestedBlock of (block as BlockTemplateBlock).template
        ?.blocks ?? []) {
        teaserIds.push(...processBlock(nestedBlock as BaseBlock<BlockType>));
      }
      return teaserIds;
    }

    if (isTeaserSlotsBlock(block)) {
      return extractTeasers(block as unknown as FullTeaserSlotsBlockFragment);
    }

    return [];
  };

  const load = (blocks: BaseBlock<BlockType>[]) =>
    service.loadBlocks(blocks, { onlyDisplayed: false });

  const loadTeaserIds = async (blocks: BaseBlock<BlockType>[]) =>
    (await load(blocks)).flatMap(block =>
      processBlock(block as BaseBlock<BlockType>)
    );

  const pool = (from: number, to: number) =>
    Array.from({ length: to - from + 1 }, (_, i) => `article_pool_${from + i}`);

  it('should autofill teaser slots nested in flex blocks', async () => {
    expect(
      await loadTeaserIds([
        mockFlexBlock({ blocks: [mockBlockWithAlignment()] }),
      ])
    ).toEqual(pool(1, 8));
  });

  describe('hidden blocks', () => {
    const hide = <T extends BaseBlock<BlockType>>(block: T) =>
      ({ ...block, disabled: true }) as T;

    it('should autofill teasers that are only placed manually in hidden blocks', async () => {
      const [, visible] = await load([
        hide(mockManualTeaserSlotsBlock('article_pool_1')),
        mockTeaserSlotsBlock(),
      ]);

      expect(processBlock(visible as BaseBlock<BlockType>)).toEqual(pool(1, 8));
    });

    it('should not take autofill teasers away from visible blocks', async () => {
      const [hidden, visible] = await load([
        hide(mockTeaserSlotsBlock()),
        mockTeaserSlotsBlock(),
      ]);

      // hidden blocks are still populated for the editor
      expect(processBlock(hidden as BaseBlock<BlockType>)).toEqual(pool(1, 8));
      expect(processBlock(visible as BaseBlock<BlockType>)).toEqual(pool(1, 8));
    });

    it('should treat blocks nested in hidden flex blocks and templates as hidden', async () => {
      mockTemplates = {
        manual: {
          id: 'manual',
          blocks: [mockManualTeaserSlotsBlock('article_pool_2')],
        },
      };

      const result = await load([
        hide(
          mockFlexBlock({
            blocks: [
              mockBlockWithAlignment({
                block: mockManualTeaserSlotsBlock('article_pool_1'),
              }),
              mockBlockWithAlignment(),
            ],
          })
        ),
        hide(mockBlockTemplateBlock('manual')),
        mockTeaserSlotsBlock(),
      ]);

      expect(processBlock(result[2] as BaseBlock<BlockType>)).toEqual(
        pool(1, 8)
      );
    });

    it('should autofill teasers placed manually in hidden blocks of a template', async () => {
      mockTemplates = {
        mixed: {
          id: 'mixed',
          blocks: [
            hide(mockManualTeaserSlotsBlock('article_pool_1')),
            mockTeaserSlotsBlock(),
          ],
        },
      };

      expect(await loadTeaserIds([mockBlockTemplateBlock('mixed')])).toEqual([
        'article_pool_1',
        ...pool(1, 8),
      ]);
    });
  });

  describe('blocks outside their timing', () => {
    const offAir = <T extends BaseBlock<BlockType>>(block: T) =>
      ({ ...block, timing: { from: new Date('2100-01-01T00:00:00Z') } }) as T;

    it('should autofill teasers that are only placed manually in off-air blocks', async () => {
      const [, visible] = await load([
        offAir(mockManualTeaserSlotsBlock('article_pool_1')),
        mockTeaserSlotsBlock(),
      ]);

      expect(processBlock(visible as BaseBlock<BlockType>)).toEqual(pool(1, 8));
    });

    it('should not take autofill teasers away from visible blocks', async () => {
      const [offAirBlock, visible] = await load([
        offAir(mockTeaserSlotsBlock()),
        mockTeaserSlotsBlock(),
      ]);

      expect(processBlock(offAirBlock as BaseBlock<BlockType>)).toEqual(
        pool(1, 8)
      );
      expect(processBlock(visible as BaseBlock<BlockType>)).toEqual(pool(1, 8));
    });

    it('should treat blocks nested in off-air flex blocks as off air', async () => {
      const [, visible] = await load([
        offAir(
          mockFlexBlock({
            blocks: [
              mockBlockWithAlignment({
                block: mockManualTeaserSlotsBlock('article_pool_1'),
              }),
            ],
          })
        ),
        mockTeaserSlotsBlock(),
      ]);

      expect(processBlock(visible as BaseBlock<BlockType>)).toEqual(pool(1, 8));
    });
  });

  it('loads the same blocks only once', async () => {
    const blocks = [mockTeaserSlotsBlock()] as BaseBlock<BlockType>[];

    await load(blocks);
    await service.loadBlocks(blocks, { onlyDisplayed: true });
    await service.nextChange(blocks);

    expect(mockArticleService.getArticles).toHaveBeenCalledTimes(1);
  });

  describe('onlyDisplayed', () => {
    const hide = <T extends BaseBlock<BlockType>>(block: T) =>
      ({ ...block, disabled: true }) as T;

    beforeEach(() => {
      mockTemplates = {
        mixed: {
          id: 'mixed',
          blocks: [
            mockTeaserSlotsBlock(),
            hide(mockManualTeaserSlotsBlock('article_pool_1')),
          ],
        },
      };
    });

    it('drops hidden blocks', async () => {
      const blocks = await service.loadBlocks(
        [mockTeaserSlotsBlock(), hide(mockTeaserSlotsBlock())],
        { onlyDisplayed: true }
      );

      expect(blocks).toHaveLength(1);
    });

    it('drops blocks that are outside their timing', async () => {
      const timed = {
        ...mockTeaserSlotsBlock(),
        timing: { from: new Date('2100-01-01T00:00:00Z') },
      } as BaseBlock<BlockType>;

      expect(
        await service.loadBlocks([timed], { onlyDisplayed: true })
      ).toEqual([]);
    });

    it('leaves the full tree intact for a later request of every block', async () => {
      const blocks = [
        mockFlexBlock({
          blocks: [
            mockBlockWithAlignment(),
            mockBlockWithAlignment({
              block: hide(mockManualTeaserSlotsBlock('article_pool_1')),
            }),
          ],
        }),
      ];

      await service.loadBlocks(blocks, { onlyDisplayed: true });
      const [flex] = (await load(blocks)) as FlexBlock[];

      expect(flex.blocks).toHaveLength(2);
    });

    it('serves a filtered template its blocks without loading it again', async () => {
      const [block] = (await service.loadBlocks(
        [mockBlockTemplateBlock('mixed')],
        { onlyDisplayed: true }
      )) as BlockTemplateBlock[];
      const template = block.template as BlockTemplate;
      const calls = mockArticleService.getArticles.mock.calls.length;

      expect(
        await service.loadTemplateBlocks(template, { onlyDisplayed: true })
      ).toHaveLength(1);
      expect(
        await service.loadTemplateBlocks(template, { onlyDisplayed: false })
      ).toHaveLength(2);
      expect(mockArticleService.getArticles).toHaveBeenCalledTimes(calls);
    });
  });

  describe('nextChange', () => {
    it('is null while no block is timed', async () => {
      expect(await service.nextChange([mockTeaserSlotsBlock()])).toBeNull();
    });

    it('works out the next change of the same blocks only once', () => {
      const blocks = [mockTeaserSlotsBlock()];

      expect(service.nextChange(blocks)).toBe(service.nextChange(blocks));
    });

    it('does not load teasers', async () => {
      await service.nextChange([mockTeaserSlotsBlock()]);

      expect(mockArticleService.getArticles).not.toHaveBeenCalled();
    });

    it('reads timings stored as strings', async () => {
      const at = new Date(service.now.getTime() + 60 * 60 * 1000);

      expect(
        await service.nextChange([
          {
            ...mockTeaserSlotsBlock(),
            timing: { from: at.toISOString() },
          } as unknown as BaseBlock<BlockType>,
        ])
      ).toEqual(at);
    });

    it('sees the timing of blocks inside templates', async () => {
      const at = new Date(service.now.getTime() + 60 * 60 * 1000);
      mockTemplates = {
        timed: {
          id: 'timed',
          blocks: [{ ...mockTeaserSlotsBlock(), timing: { from: at } }],
        },
      };

      expect(
        await service.nextChange([mockBlockTemplateBlock('timed')])
      ).toEqual(at);
    });
  });

  describe('block templates', () => {
    beforeEach(() => {
      mockTemplates = {
        slots: {
          id: 'slots',
          blocks: [
            mockTeaserSlotsBlock(),
            mockTeaserSlotsBlockWithManualTeaser(),
          ],
        },
        manual: {
          id: 'manual',
          blocks: [mockManualTeaserSlotsBlock('article_pool_1')],
        },
        flex: {
          id: 'flex',
          blocks: [mockFlexBlock({ blocks: [mockBlockWithAlignment()] })],
        },
        nested: { id: 'nested', blocks: [mockBlockTemplateBlock('slots')] },
        circular: {
          id: 'circular',
          blocks: [mockBlockTemplateBlock('circular'), mockTeaserSlotsBlock()],
        },
      };
    });

    it('should populate the teaser slots of a template', async () => {
      const [block] = (await load([
        mockBlockTemplateBlock('slots'),
      ])) as BlockTemplateBlock[];

      expect(processBlock(block)).toEqual([
        ...pool(1, 8),
        'article_pool_100',
        'article_pool_9',
      ]);
      expect(
        await service.loadTemplateBlocks(block.template as BlockTemplate, {
          onlyDisplayed: false,
        })
      ).toBe(block.template?.blocks);
    });

    it('should not repeat teasers between templates and surrounding blocks', async () => {
      expect(
        await loadTeaserIds([
          mockTeaserSlotsBlock(),
          mockBlockTemplateBlock('manual'),
          mockTeaserSlotsBlock(),
        ])
      ).toEqual([...pool(2, 9), 'article_pool_1', ...pool(10, 17)]);
    });

    it('should populate templates nested in flex blocks and flex blocks nested in templates', async () => {
      expect(
        await loadTeaserIds([
          mockFlexBlock({
            blocks: [
              mockBlockWithAlignment({ block: mockBlockTemplateBlock('flex') }),
            ],
          }),
        ])
      ).toEqual(pool(1, 8));
    });

    it('should populate templates nested in templates', async () => {
      expect(await loadTeaserIds([mockBlockTemplateBlock('nested')])).toEqual([
        ...pool(1, 8),
        'article_pool_100',
        'article_pool_9',
      ]);
    });

    it('should not expand circular templates', async () => {
      const [block] = (await load([
        mockBlockTemplateBlock('circular'),
      ])) as BlockTemplateBlock[];

      const [circular] = (block.template?.blocks ?? []) as BlockTemplateBlock[];

      expect(circular.template).toBeNull();
      expect(processBlock(block)).toEqual(pool(1, 8));
    });

    it('should keep unknown templates to be resolved as null', async () => {
      const [block] = (await load([
        mockBlockTemplateBlock('deleted'),
      ])) as BlockTemplateBlock[];

      expect(block.template).toBeUndefined();
    });

    it('should populate a template queried on its own without sharing loaded teasers', async () => {
      expect(await loadTeaserIds([mockTeaserSlotsBlock()])).toEqual(pool(1, 8));

      const templateBlocks = await service.loadTemplateBlocks(
        mockTemplates['slots'] as unknown as BlockTemplate,
        { onlyDisplayed: false }
      );

      expect(
        templateBlocks.flatMap(block =>
          processBlock(block as BaseBlock<BlockType>)
        )
      ).toEqual([...pool(1, 8), 'article_pool_100', 'article_pool_9']);

      expect(await loadTeaserIds([mockTeaserSlotsBlock()])).toEqual(
        pool(9, 16)
      );
    });
  });

  it('should return unique teasers', async () => {
    const result = await load(revisionBlocks);
    const shouldBeUniqueTeaserIds: string[] = [];

    for (const block of result as BaseBlock<BlockType>[]) {
      shouldBeUniqueTeaserIds.push(...processBlock(block));
    }

    //console.log('shouldBeUniqueTeaserIds:', shouldBeUniqueTeaserIds);

    const unique = (x: string, i: number, arr: string[]) =>
      arr.indexOf(x) === i;

    const naturalSortAsc = (a: string, b: string) =>
      ('' + a).localeCompare(b, undefined, {
        numeric: true,
        sensitivity: 'base',
      });

    const filteredTeaserIds = shouldBeUniqueTeaserIds.filter(unique);
    const sortedTeaserIds = [...shouldBeUniqueTeaserIds].sort(naturalSortAsc);
    // in the sorted array, move id of manually added teaser (id 'article_pool_100')...
    // ...to its expected position (after 'article_pool_56')
    const manualTeaserId = 'article_pool_100';
    const indexOfManualTeaser = sortedTeaserIds.indexOf(manualTeaserId);
    if (indexOfManualTeaser > -1) {
      sortedTeaserIds.splice(indexOfManualTeaser, 1);
      const expectedIndex = shouldBeUniqueTeaserIds.indexOf(manualTeaserId);
      sortedTeaserIds.splice(expectedIndex, 0, manualTeaserId);
    }

    const hasItem66 = shouldBeUniqueTeaserIds.some(
      item => item === 'article_pool_66'
    );
    const hasItem67 = shouldBeUniqueTeaserIds.some(
      item => item === 'article_pool_67'
    );

    // teasers from grid-flex-block should not be repeated in autofilled teaser-slots-blocks
    expect(hasItem66).toBe(false);
    expect(hasItem67).toBe(false);

    //      1 teaser-slots-block x 8 slots --> 8 teasers
    // +    1 flex-blocks
    // +      7 teaser-slots-blocks x 8 slots --> 56 teasers
    // +      1 teaser-slots-blocks x (1 manual slot + 1 autofill slot) --> 2 teasers
    // +    1 flex-blocks x 7 teaser-slots-blocks x 8 slots --> 56 teasers
    // --------------------------------------------------------
    // =  122 teasers expected
    //
    expect(shouldBeUniqueTeaserIds.length).toEqual(122);

    // teaser ids should be in the order they were loaded into blocks
    expect(sortedTeaserIds.join(',')).toEqual(
      shouldBeUniqueTeaserIds.join(',')
    );

    // all ids should be unique
    expect(filteredTeaserIds).toEqual(shouldBeUniqueTeaserIds);

    // snapshot test the full structure
    expect(result).toMatchSnapshot();
  });
});
